#pragma once

#include <stddef.h>
#include <stdint.h>

namespace e84stream {
constexpr size_t kHeaderBytes = 24;
constexpr size_t kMaxPayload = 1280;
constexpr size_t kAudioBytes = 640;
constexpr size_t kQueueFrames = 64;
constexpr size_t kPrebufferFrames = 32;
// API may have another 10 unacknowledged frames in flight: 48+10 < 64.
constexpr size_t kCreditFrames = 48;

enum class Type : uint8_t {
  Hello = 1, Ready, CallStart, CallStarted, InputStart, InputAudio, InputEnd,
  OutputStart, OutputAudio, OutputEnd, PlaybackDone, Listen, CallEnd, CallEnded,
  Cancel, Error, Ping, Pong, NoReply, AudioAck
};
struct Header {
  Type type = Type::Error;
  uint8_t flags = 0;
  uint32_t session = 0;
  uint32_t turn = 0;
  uint32_t sequence = 0;
  uint32_t length = 0;
};
bool decodeHeader(const uint8_t* bytes, Header& header);
void encodeHeader(const Header& header, uint8_t* bytes);
bool tokenMatches(const uint8_t* payload, size_t length, const char* expected);

// Buffer memory stays owned until the speaker has released its request.
class AudioQueue {
 public:
  bool push(const uint8_t* pcm, size_t bytes);
  const int16_t* samples(size_t offset = 0) const;
  size_t sampleCount(size_t offset = 0) const;
  void pop();
  void clear();
  size_t size() const { return size_; }
  bool full() const { return size_ == kQueueFrames; }
 private:
  struct Frame { int16_t pcm[kAudioBytes / 2]; uint16_t samples = 0; };
  Frame frames_[kQueueFrames];
  size_t head_ = 0;
  size_t size_ = 0;
};

enum class Action {
  Invalid, Pending, StartCall, Started, StartOutput, Audio, EndOutput,
  EndCall, Ended, Cancel, Pong
};

// State transitions independent of sockets and hardware, tested on the host.
class Session {
 public:
  void begin(uint32_t session);
  Action accept(const Header& header);
  bool callStarted();
  bool playbackFinished();
  bool callEnded();
  uint32_t id() const { return id_; }
  uint32_t turn() const { return turn_; }
  uint32_t frames() const { return frames_; }
  bool outputActive() const { return phase_ == Phase::Output; }
  bool outputEnded() const { return outputEnded_; }
  bool closed() const { return phase_ == Phase::Ended || phase_ == Phase::Cancelled; }
 private:
  enum class Phase { Initial, Starting, Idle, Output, Ending, Ended, Cancelled };
  Phase phase_ = Phase::Initial;
  uint32_t id_ = 0;
  uint32_t turn_ = 0;
  uint32_t frames_ = 0;
  bool hasOutput_ = false;
  bool outputEnded_ = false;
  bool endRequested_ = false;
  bool started_ = false;
};

// Prevent a disconnected connection from replaying an old physical operation.
// IDs must be freshly generated by E84; entries intentionally have no time TTL.
class SessionHistory {
 public:
  bool contains(uint32_t session) const;
  void remember(uint32_t session);
 private:
  uint32_t ids_[64] = {};
  size_t next_ = 0;
};
}  // namespace e84stream
