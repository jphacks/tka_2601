def staff_reason_code(value: str) -> str:
    """Return the canonical enum value for a reviewed note or an existing code."""
    if value in STAFF_REASON_LABELS:
        return value
    try:
        return STAFF_REASON_TEXT_TO_CODE[value]
    except KeyError as exc:
        raise ValueError(f"unknown staff reason: {value!r}") from exc
