/// `STAFF_REASON_LABELS.get(code)`.
pub fn staff_reason_label(code: &str) -> Option<&'static str> {
    STAFF_REASON_LABELS
        .iter()
        .find(|(key, _)| *key == code)
        .map(|(_, label)| *label)
}

/// `code in STAFF_REASON_LABELS`.
pub fn is_staff_reason(code: &str) -> bool {
    staff_reason_label(code).is_some()
}

/// `staff_reason_code`: the canonical code for a reviewed note or an existing code.
pub fn staff_reason_code(value: &str) -> Result<&'static str, PolicyError> {
    if let Some((code, _)) = STAFF_REASON_LABELS.iter().find(|(key, _)| *key == value) {
        return Ok(code);
    }
    STAFF_REASON_TEXT_TO_CODE
        .iter()
        .find(|(key, _)| *key == value)
        .map(|(_, code)| *code)
        .ok_or_else(|| PolicyError(format!("unknown staff reason: {}", py_repr(value))))
}

fn py_repr(value: &str) -> String {
    // Python's repr() of a str without quotes or backslashes uses single quotes.
    if value.contains('\'') && !value.contains('"') {
        format!("\"{value}\"")
    } else {
        format!("'{}'", value.replace('\\', "\\\\").replace('\'', "\\'"))
    }
}
